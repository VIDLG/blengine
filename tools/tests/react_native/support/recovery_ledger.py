"""RN recovery ledger projections over the Peripheral BTP emulator."""

from __future__ import annotations

import json
from pathlib import Path
from unittest.mock import patch

from tests.peripherals.nrf52840 import recovery_ten as physical
from tests.peripherals.nrf52840.support.recovery_emulator import Harness
from tests.peripherals.nrf52840.support.session_receipts import fake_attempt
from tools.react_native import recovery_ten_ledger as api


class SyntheticHarness(Harness):
    """Reuse the actual provider coordinator with its existing synthetic wire."""

    def __init__(
        self,
        directory: Path,
        platform: str,
        fault: str,
        require_local_name: bool = False,
    ) -> None:
        prepare = api.session.prepare_session

        def prepare_with_name_policy(contract: Path, profile: Path, *args, **kwargs):
            document = json.loads(profile.read_text(encoding="utf-8"))
            document["advertising"]["require_local_name"] = require_local_name
            profile.write_text(json.dumps(document), encoding="utf-8")
            return prepare(contract, profile, *args, **kwargs)

        # Freeze and hash the synthetic policy before the coordinator sees it.
        with (
            patch.object(
                api.session, "prepare_session", side_effect=prepare_with_name_policy
            ),
            patch(
                "tests.peripherals.nrf52840.support.recovery_emulator.fake_attempt",
                side_effect=lambda root: fake_attempt(
                    root, service="fd500000-0000-4000-8000-000000000000"
                ),
            ),
        ):
            super().__init__(directory, platform, fault)

    def identity(self) -> dict[str, object]:
        return {**super().identity(), "source": "launch"}

    def append(self, *markers: str) -> None:
        normalized = []
        for marker in markers:
            if marker.startswith("native:signal:"):
                value = json.loads(marker.removeprefix("native:signal:"))
                value["source"] = "payload-url"
                marker = "native:signal:" + json.dumps(value)
            normalized.append(marker)
        super().append(*normalized)


def synthetic_events(harness: Harness) -> list[str]:
    """Expand synthetic source markers into exact native projection JSON shapes.

    This is deliberately not a native count factory or a physical proof producer.
    The physical schema is generated by Harness.run()/the actual coordinator.
    """
    lines = []
    cycle = 0
    profile = harness.fixture._profile

    def event(kind: str, offset: int | None = None, **fields: object) -> None:
        body = {key: None for key in api._EVENT_FIELDS}
        body.update(
            kind=kind,
            runId=harness.plan.session_id,
            nonce="synthetic-one-runtime",
            cycle=cycle,
            commandId=None if offset is None else str(10000 + cycle * 100 + offset),
            **fields,
        )
        lines.append(physical.PREFIX + "event:" + json.dumps(body))

    def terminal(offset: int) -> None:
        event("commandCompleted", offset)

    def database(recovered: bool) -> list[dict]:
        # Native allocation IDs intentionally live outside the command namespace;
        # service/descriptor zero is permitted by the actual u64 contract.
        ids = {
            "read-write": 98765 if recovered else 98764,
            "updates": 98766 if recovered else 98765,
            "indications": 98767,
            "read-only": 98768,
            "write-only": 98769,
        }
        characteristics = []
        for declared in profile.characteristics:
            characteristic = {
                "id": str(ids[declared.role]),
                "uuid": declared.uuid,
                **{
                    key: bool(declared.properties & api.PROPERTY_BITS[prop])
                    for key, prop in api._PROPERTIES.items()
                },
                "descriptors": [],
            }
            if declared.requires_ccc:
                characteristic["descriptors"] = [
                    {
                        "id": "900000" if declared.role == "updates" else "900001",
                        "uuid": api._CCC,
                    }
                ]
            characteristics.append(characteristic)
        return [
            {
                "id": "0",
                "uuid": profile.service_uuid,
                "primary": True,
                "characteristics": characteristics,
            }
        ]

    for line in harness.lines:
        marker = line.removeprefix(physical.PREFIX)
        if marker.startswith("cycle:"):
            cycle = int(marker.split(":")[1])
        b = 10000 + cycle * 100
        if ":initialize:passed:" in marker:
            event(
                "adapterSnapshotChanged",
                0,
                adapterState="PoweredOn",
                scanAuthorization="Authorized",
            )
            terminal(0)
        elif ":scan-budget-started:" in marker:
            event("scanStarted", 2, scanSessionId=str(b + 1))
            terminal(2)
        elif ":scan:passed:" in marker:
            if harness.platform != "android":
                event("scanStarted", 2, scanSessionId=str(b + 1))
                terminal(2)
            event(
                "advertisementObserved",
                scanSessionId=str(b + 1),
                peripheralId="88",
                rssi=-62,
                localName=profile.local_name,
                advertisedServices=[profile.service_uuid],
            )
            event("scanStopped", 3, scanSessionId=str(b + 1))
            terminal(3)
        elif ":connected:passed:" in marker or ":recovery-connected:passed:" in marker:
            recovered = ":recovery-connected:" in marker
            offset, route = (11, 10) if recovered else (5, 4)
            for state in ("Connecting", "Connected"):
                event(
                    "connectionStateChanged",
                    offset,
                    connectionId=str(b + route),
                    connectionState=state,
                )
            terminal(offset)
        elif ":gatt:passed:" in marker or ":recovery-gatt:passed:" in marker:
            recovered = ":recovery-gatt:" in marker
            offset, connection, gatt = (13, 10, 14) if recovered else (7, 4, 6)
            event(
                "gattDiscovered",
                offset,
                connectionId=str(b + connection),
                gattSessionId=str(b + gatt),
                gattServices=database(recovered),
            )
            terminal(offset)
        elif ":notification-enable:passed:" in marker:
            event(
                "notificationStateChanged",
                9,
                connectionId=str(b + 4),
                gattSessionId=str(b + 6),
                subscriptionId=str(b + 8),
                characteristicId="98765",
                notificationState="Enabled",
                actualNotificationMode="Notification",
            )
            terminal(9)
        elif ":notification-value:passed:" in marker:
            event(
                "notificationReceived",
                connectionId=str(b + 4),
                gattSessionId=str(b + 6),
                subscriptionId=str(b + 8),
                characteristicId="98765",
                value=[239],
            )

        elif ":recovery-read:passed:" in marker:
            event(
                "characteristicRead",
                15,
                connectionId=str(b + 10),
                gattSessionId=str(b + 14),
                characteristicId="98765",
                value=[0],
            )
            terminal(15)
        elif ":recovery-disconnected:passed:" in marker:
            event(
                "connectionStateChanged",
                12,
                connectionId=str(b + 10),
                connectionState="Disconnected",
            )
            terminal(12)
        lines.append(line)
    return lines
